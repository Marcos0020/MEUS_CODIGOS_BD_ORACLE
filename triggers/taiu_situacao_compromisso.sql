CREATE OR REPLACE TRIGGER MYSCHEMA.SITUACAOCOMPROMISSO_GOL
AFTER UPDATE OF ID_SITUACAOCOMPROMISSO ON APP.JUR_COMPROMISSO
FOR EACH ROW
when (
    NEW.ID_SITUACAOCOMPROMISSO = 'C1B2C3D4-3333-CCCC-0001-000000000001'
    AND NEW.ID_TIPOCOMPROMISSO = 'D1B2C3D4-4444-DDDD-0002-000000000002'
)
DECLARE
    PRAGMA AUTONOMOUS_TRANSACTION;  -- Evita erro de trigger mutante

BEGIN

for rec0 in (SELECT id_assunto
       FROM   app.jur_assunto
       WHERE   id_tipoassunto ='B1B2C3D4-2222-BBBB-0002-000000000002'
       AND   id_assunto = :NEW.id_Assunto) LOOP

   --DATA DA ALTERAÇÃO +10 - TIPO DE AGENDA:JUNTADA DE GUIA - DESCRIÇÃO: JUNTADA DE GUIA
   INSERT INTO app.jur_compromisso
       (DATA,
       DESCRICAO,
       DATA_INCLUSAO,
       USUARIO_INCLUSAO,
       ID_SITUACAOCOMPROMISSO,
       ID_TIPOCOMPROMISSO,
       ID_ASSUNTO,
       ID_LICENCA,
       CODIGO,
       ID_COMPROMISSO)
    VALUES (
    MYSCHEMA.PROXIMA_DATA_UTIL(SYSDATE + 10),
    'JUNTADA DE GUIA',
    sysdate,
    'SYSTEM_TRIGGER',
    'C1B2C3D4-3333-CCCC-0002-000000000002',
    'D1B2C3D4-4444-DDDD-0005-000000000005', -- JUNTADA DE GUIA
    rec0.ID_ASSUNTO,
    1,
  abs(dbms_random.random)*(-1),
    app.uuid
    );
    -- Confirma a transação autônoma
    COMMIT;

   END LOOP;
END;